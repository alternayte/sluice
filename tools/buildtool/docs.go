func mcpToolsPage() (string, error) {
	var b strings.Builder
	b.WriteString("This page lists the tools of the MCP server at `/mcp`. The assistant in the web UI uses the same tools.\n\n")
	b.WriteString("A tool runs with the role of the API token. A mutating tool runs at once over MCP; in the assistant it waits for your confirmation. " +
		"Results of execution tools are masked: a secret value shows as `***`.\n\n")
	b.WriteString("| Tool | Role | Mutating | MCP | Description |\n|---|---|---|---|---|\n")
	tools := ai.Tools()
	for _, t := range tools {
		mcp := "yes"
		if t.AssistantOnly {
			mcp = "no"
		}
		mut := "no"
		if t.Mutating {
			mut = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", t.Name, t.Role, mut, mcp, cell(t.Description))
	}
	for _, t := range tools {
		var schema struct {
			Properties map[string]struct {
				Type        string `json:"type"`
				Description string `json:"description"`
			} `json:"properties"`
			Required []string `json:"required"`
		}
		if err := json.Unmarshal(t.Schema, &schema); err != nil {
			return "", fmt.Errorf("tool %s: %w", t.Name, err)
		}
		if len(schema.Properties) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n| Argument | Type | Required | Description |\n|---|---|---|---|\n", t.Name)
		names := make([]string, 0, len(schema.Properties))
		for n := range schema.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			p := schema.Properties[n]
			req := "no"
			if slices.Contains(schema.Required, n) {
				req = "yes"
			}
			typ := p.Type
			if typ == "" {
				typ = "any"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", n, typ, req, cell(p.Description))
		}
	}
	return page("MCP tools", "The tools of the MCP server and the assistant.", "internal/ai/tools.go", b.String()), nil
}

