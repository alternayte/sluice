// cell escapes text for a Markdown table cell: a pipe ends the cell, and <word> would be HTML.
func cell(s string) string {
	return strings.NewReplacer("|", "\\|", "<", "&lt;", ">", "&gt;").Replace(s)
}

// escapeTables escapes < and > outside code spans in the table rows of a Markdown document.
func escapeTables(md string) string {
	lines := strings.Split(md, "\n")
	for i, l := range lines {
		if !strings.HasPrefix(l, "|") {
			continue
		}
		parts := strings.Split(l, "`")
		for j := 0; j < len(parts); j += 2 {
			parts[j] = strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(parts[j])
		}
		lines[i] = strings.Join(parts, "`")
	}
	return strings.Join(lines, "\n")
}

// page wraps a generated body in Starlight frontmatter.
func page(title, description, source, body string) string {
	return fmt.Sprintf("---\ntitle: %s\ndescription: %s\n---\n\n"+generated+"\n\n%s", title, description, source, strings.TrimLeft(body, "\n"))
}

// stripTitle removes the leading "# Title" and "Generated from" lines of a Markdown document.
func stripTitle(doc string) string {
	lines := strings.Split(doc, "\n")
	var out []string
	for i, l := range lines {
		if i < 4 && (strings.HasPrefix(l, "# ") || strings.HasPrefix(l, "Generated from")) {
			continue
		}
		out = append(out, l)
	}
	return strings.TrimLeft(strings.Join(out, "\n"), "\n")
}

