// writeReferencePages writes the generated Reference pages.
func writeReferencePages() error {
	pages, err := referencePages()
	if err != nil {
		return err
	}
	for _, p := range slices.Sorted(mapsKeys(pages)) {
		content, err := pages[p]()
		if err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		if err := writeFile(p, content); err != nil {
			return err
		}
	}
	return nil
}

func mapsKeys[V any](m map[string]V) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// fenceRe finds a fenced code block, also one indented in a list or a component: its
// indentation, its info string and its body.
var fenceRe = regexp.MustCompile("(?ms)^([ \\t]*)```([^\\n]*)\\n(.*?)^[ \\t]*```[ \\t]*$")

// dedent removes the indentation of a fence from each line of its body.
func dedent(body []byte, indent string) []byte {
	if indent == "" {
		return body
	}
	lines := bytes.Split(body, []byte("\n"))
	for i, l := range lines {
		lines[i] = bytes.TrimPrefix(l, []byte(indent))
	}
	return bytes.Join(lines, []byte("\n"))
}

var shellLangs = map[string]bool{"sh": true, "bash": true, "shell": true, "console": true}

// sluiceCmdRe finds a sluice command in a shell sample and its first two words. A command
// starts a line (after an optional "$ " prompt) or follows &&, ||, ;, | or $(. So a namespace
// argument such as "kubectl -n sluice rollout" or "cd sluice" is not a command.
var sluiceCmdRe = regexp.MustCompile(`(?m)(?:^[ \t]*(?:\$[ \t]+)?|&&[ \t]*|\|\|[ \t]*|;[ \t]*|\|[ \t]*|\$\([ \t]*)sluice[ \t]+([a-z][a-z-]*)(?:[ \t]+([a-z][a-z-]*))?`)

// sampleKinds validate a YAML sample of each kind. A nil validator only parses the YAML.
var sampleKinds = map[string]func(body []byte) error{
	"flow":      func(b []byte) error { return validateSample("sample.flow.yaml", b) },
	"namespace": func(b []byte) error { return validateSample("namespace.yaml", b) },
	"compose":   nil,
	"workflow":  nil,
	"k8s":       nil,
	"helm":      nil,
}

// validateSample validates a flow or namespace.yaml sample as Sluice does. A sample can name
// script files that the docs do not hold, so file_not_found does not count.
func validateSample(path string, body []byte) error {
	res := flow.ValidateNamespace(map[string][]byte{path: body}).Result()
	var msgs []string
	for _, f := range res.Files {
		for _, e := range f.Errors {
			if e.Code == "file_not_found" {
				continue
			}
			msgs = append(msgs, fmt.Sprintf("line %d: %s %s: %s", e.Line, e.Code, e.Path, e.Message))
		}
	}
	if len(msgs) > 0 {
		return errors.New(strings.Join(msgs, "; "))
	}
	return nil
}

func kindNames() string {
	return strings.Join(slices.Sorted(mapsKeys(sampleKinds)), ", ")
}

// commandNames returns the first word and the two-word names of the CLI commands.
func commandNames() (map[string]bool, map[string]bool) {
	first, full := map[string]bool{}, map[string]bool{}
	for _, c := range app.Commands() {
		w := strings.Fields(c[0])
		first[w[0]] = true
		full[c[0]] = true
	}
	return first, full
}

// checkSamples validates each YAML sample of the docs, and checks each sluice command of a
// shell sample against the CLI.
func checkSamples() ([]string, error) {
	first, full := commandNames()
	var problems []string
	err := filepath.WalkDir(docsDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".md") && !strings.HasSuffix(p, ".mdx") {
			return err
		}
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for _, m := range fenceRe.FindAllSubmatchIndex(src, -1) {
			info := strings.Fields(string(src[m[4]:m[5]]))
			body := dedent(src[m[6]:m[7]], string(src[m[2]:m[3]]))
			line := bytes.Count(src[:m[0]], []byte("\n")) + 1
			if len(info) == 0 {
				continue
			}
			switch lang := info[0]; {
			case lang == "yaml" || lang == "yml":
				kind := ""
				for _, w := range info[1:] {
					if _, ok := sampleKinds[w]; ok {
						kind = w
					}
				}
				if kind == "" {
					problems = append(problems, fmt.Sprintf("%s:%d: a YAML sample needs its kind, for example ```yaml flow. Kinds: %s", p, line, kindNames()))
					continue
				}
				var n yaml.Node
				if err := yaml.Unmarshal(body, &n); err != nil {
					problems = append(problems, fmt.Sprintf("%s:%d: the YAML does not parse: %v", p, line, err))
					continue
				}
				if v := sampleKinds[kind]; v != nil {
					if err := v(body); err != nil {
						problems = append(problems, fmt.Sprintf("%s:%d: the %s sample is invalid: %v", p, line, kind, err))
					}
				}
			case shellLangs[lang]:
				for _, c := range sluiceCmdRe.FindAllSubmatch(body, -1) {
					w1, w2 := string(c[1]), string(c[2])
					if full[w1+" "+w2] || full[w1] {
						continue
					}
					if first[w1] {
						problems = append(problems, fmt.Sprintf("%s:%d: `sluice %s %s` is not a command. `sluice help` lists the commands.", p, line, w1, w2))
					} else {
						problems = append(problems, fmt.Sprintf("%s:%d: `sluice %s` is not a command. `sluice help` lists the commands.", p, line, w1))
					}
				}
			}
		}
		return nil
	})
	return problems, err
}

var envRe = regexp.MustCompile(`SLUICE_[A-Z][A-Z0-9_]*[A-Z0-9]`)

// checkEnvVars fails when a SLUICE_ variable that the code reads is missing from the env page.
// Test helpers do not count.
func checkEnvVars() ([]string, error) {
	pageSrc, err := os.ReadFile(envPage)
	if err != nil {
		return nil, fmt.Errorf("the env page: %w", err)
	}
	seen := map[string]bool{}
	for _, root := range []string{"cmd", "internal"} {
		err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() && d.Name() == "testutil" {
				return filepath.SkipDir
			}
			if d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
				return nil
			}
			src, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			for _, v := range envRe.FindAll(src, -1) {
				// SLUICE_SECRET is the prefix of SLUICE_SECRET_<KEY>, which the page names as a pattern.
				if string(v) != "SLUICE_SECRET" {
					seen[string(v)] = true
				}
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	var problems []string
	for _, v := range slices.Sorted(mapsKeys(seen)) {
		if !bytes.Contains(pageSrc, []byte("`"+v+"`")) {
			problems = append(problems, fmt.Sprintf("%s does not name %s, which the code reads.", envPage, v))
		}
	}
	return problems, nil
}

// cmdDocsRefCheck fails when a generated Reference page is stale, a YAML sample is invalid, a
// shell sample runs a sluice command that does not exist, or the env page misses a variable.
func cmdDocsRefCheck() error {
	pages, err := referencePages()
	if err != nil {
		return err
	}
	var problems []string
	for _, p := range slices.Sorted(mapsKeys(pages)) {
		want, err := pages[p]()
		if err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		have, err := os.ReadFile(p)
		if err != nil || string(have) != want {
			problems = append(problems, fmt.Sprintf("%s is stale. Run `just gen`.", p))
		}
	}
	samples, err := checkSamples()
	if err != nil {
		return err
	}
	problems = append(problems, samples...)
	envProblems, err := checkEnvVars()
	if err != nil {
		return err
	}
	problems = append(problems, envProblems...)
	if len(problems) > 0 {
		return errors.New("the docs are not current:\n  " + strings.Join(problems, "\n  "))
	}
	fmt.Println("docs-ref-check: ok")
	return nil
}
