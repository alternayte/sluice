func cliPage() (string, error) {
	var b strings.Builder
	b.WriteString("This page lists every command of the `sluice` binary. `sluice help` prints the same list.\n\n")
	b.WriteString("Install the binary on Linux or macOS. The installer checks the download against the published checksum. " +
		"`SLUICE_VERSION` picks a release and `SLUICE_BIN_DIR` the directory:\n\n```sh\ncurl -fsSL https://raw.githubusercontent.com/alternayte/sluice/main/install.sh | sh\n```\n\n")
	b.WriteString("The client commands talk to a Sluice server. They read `SLUICE_URL` and `SLUICE_TOKEN`, " +
		"take `--output json` (or `-o json`) to print the API JSON, and exit with a code from [Exit codes](/reference/exit-codes/).\n\n")
	b.WriteString("| Command | Description |\n|---|---|\n")
	cmds := app.Commands()
	for _, c := range cmds {
		fmt.Fprintf(&b, "| `sluice %s` | %s |\n", c[0], cell(c[1]))
	}
	for _, c := range cmds {
		if !flagHelp[c[0]] {
			continue
		}
		help := helpOf(c[0])
		if help == "" {
			continue
		}
		fmt.Fprintf(&b, "\n## sluice %s\n\n%s\n\n```text\n%s\n```\n", c[0], cell(c[1]), help)
	}
	return page("CLI", "Every command of the sluice binary, with its flags.", "internal/app/cli.go", b.String()), nil
}

