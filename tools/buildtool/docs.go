// helpOf returns the flag help that a command prints for -h, or "" for a command without flags.
func helpOf(name string) string {
	var out, errb bytes.Buffer
	app.MainIO(append(strings.Fields(name), "-h"), &out, &errb)
	text := strings.TrimSpace(errb.String() + out.String())
	if !strings.Contains(text, "-") {
		return ""
	}
	return text
}

