package main

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

const forbidWordsPath = "scripts/forbid-words.txt"

// forbidRules holds the word list sections of scripts/forbid-words.txt.
type forbidRules struct {
	words     []string // forbidden in source files
	testWords []string // forbidden in test files
}

func loadForbidRules(path string) (*forbidRules, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	r := &forbidRules{}
	section := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = line
			continue
		}
		switch section {
		case "[words]":
			r.words = append(r.words, line)
		case "[test]":
			r.testWords = append(r.testWords, line)
		}
	}
	if len(r.words) == 0 || len(r.testWords) == 0 {
		return nil, errors.New("forbid word list needs [words] and [test] sections")
	}
	return r, sc.Err()
}

var forbidExts = map[string]bool{".go": true, ".ts": true, ".tsx": true, ".py": true, ".sh": true, ".yaml": true, ".yml": true}

var generatedRe = regexp.MustCompile(`(?m)^(//|#|/\*|\s\*)?.*(Code generated .* DO NOT EDIT|@generated|This file was automatically generated|auto-generated by openapi-typescript)`)

func isTestFile(p string) bool {
	base := filepath.Base(p)
	return strings.HasSuffix(base, "_test.go") ||
		strings.Contains(base, ".test.") || strings.Contains(base, ".spec.") ||
		strings.HasPrefix(filepath.ToSlash(p), "tests/")
}

func isGenerated(content []byte) bool {
	head := content
	if len(head) > 2048 {
		head = head[:2048]
	}
	return generatedRe.Match(head)
}

// forbidFinding is one forbidden word hit.
type forbidFinding struct {
	Path string
	Line int
	Word string
}

func scanForbid(files []string, rules *forbidRules, read func(string) ([]byte, error)) ([]forbidFinding, error) {
	wordRes := make([]*regexp.Regexp, len(rules.words))
	for i, w := range rules.words {
		wordRes[i] = regexp.MustCompile(`(^|[^A-Za-z0-9_])` + regexp.QuoteMeta(w) + `($|[^A-Za-z0-9_])`)
	}
	var out []forbidFinding
	for _, p := range files {
		slash := filepath.ToSlash(p)
		if strings.HasPrefix(slash, "docs/") || slash == forbidWordsPath || strings.Contains(slash, "node_modules/") {
			continue
		}
		ext := filepath.Ext(p)
		test := isTestFile(p)
		if !forbidExts[ext] && !test {
			continue
		}
		content, err := read(p)
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				continue
			}
			return nil, err
		}
		lines := bytes.Split(content, []byte("\n"))
		if forbidExts[ext] && !isGenerated(content) {
			for i, l := range lines {
				for j, re := range wordRes {
					if re.Match(l) {
						out = append(out, forbidFinding{p, i + 1, rules.words[j]})
					}
				}
			}
		}
		if test {
			for i, l := range lines {
				for _, w := range rules.testWords {
					if bytes.Contains(l, []byte(w)) {
						out = append(out, forbidFinding{p, i + 1, w})
					}
				}
			}
		}
	}
	return out, nil
}

func repoFiles() ([]string, error) {
	out, err := exec.Command("git", "ls-files", "--cached", "--others", "--exclude-standard").Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files: %w", err)
	}
	var files []string
	for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if l != "" {
			files = append(files, l)
		}
	}
	return files, nil
}

func cmdForbid() error {
	rules, err := loadForbidRules(forbidWordsPath)
	if err != nil {
		return err
	}
	files, err := repoFiles()
	if err != nil {
		return err
	}
	found, err := scanForbid(files, rules, os.ReadFile)
	if err != nil {
		return err
	}
	for _, f := range found {
		fmt.Printf("%s:%d: forbidden %q\n", f.Path, f.Line, f.Word)
	}
	if len(found) > 0 {
		return fmt.Errorf("forbid: %d findings", len(found))
	}
	fmt.Printf("forbid: %d files clean\n", len(files))
	return nil
}
